export function iconFor(episode) {
  const title = String(episode.title || '');
  const reviewed = REVIEWED_EPISODE_ICONS[episode.code];
  // 標題換成別集時不套用舊主題，需要重新核對。
  if (reviewed?.title === title) return reviewed.icon;
  return SUBJECTS.find(([pattern]) => pattern.test(title))?.[1] || HOME_ICONS[episode.home] || '🎧';
}
